const ZoneDef& zoneDef(core::i32 index) {
    const core::i32 count = zoneCount();
    core::i32 clamped = index < 0 ? 0 : (index >= count ? count - 1 : index);
    return kZones[clamped];
}

core::i32 zoneCount() { return static_cast<core::i32>(sizeof(kZones) / sizeof(kZones[0])); }

